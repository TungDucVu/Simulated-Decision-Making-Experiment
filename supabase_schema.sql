-- 1. Create table for participant experiment responses
create table if not exists public.experiment_responses (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  participant_id text not null,
  assigned_condition text not null,
  pause_duration_sec integer default 0,
  date_completed text,
  total_experiment_time_sec numeric,

  -- Task 1: Shopping Decision (Headphones)
  task1_product_choice text,
  task1_initial_choice text,
  task1_changed text,
  task1_decision_time_sec numeric,
  task1_total_time_sec numeric,

  -- Task 2: Permissions Decision (FitLife)
  task2_permission_choice text,
  task2_initial_choice text,
  task2_changed text,
  task2_decision_time_sec numeric,
  task2_total_time_sec numeric,

  -- Task 3: Subscription Decision (StreamFlow)
  task3_subscription_choice text,
  task3_initial_choice text,
  task3_changed text,
  task3_decision_time_sec numeric,
  task3_total_time_sec numeric,

  -- form.pdf Survey Items
  t1_recall_price text,
  t1_consequence_tradeoff text,
  t1_confidence_1to7 text,
  t1_frustration_1to7 text,

  t2_recall_permissions text,
  t2_consequence_disclosure text,
  t2_confidence_1to7 text,
  t2_frustration_1to7 text,

  t3_recall_monthly_price text,
  t3_consequence_cancellation text,
  t3_confidence_1to7 text,
  t3_frustration_1to7 text,

  post_regret_1to7 text,
  post_rushed_1to5 text,
  post_ecommerce_freq text,
  post_impulsive_click_1to7 text,
  post_prior_preference text,
  participant_feedback text,

  -- Complete raw JSON object for flexible future analyses
  raw_data jsonb
);

-- 2. Enable Row Level Security (RLS)
alter table public.experiment_responses enable row level security;

-- 3. Allow anonymous participant submissions (INSERT)
create policy "Allow anonymous inserts"
  on public.experiment_responses
  for insert
  with check (true);

-- 4. Allow reading responses (SELECT)
create policy "Allow read access"
  on public.experiment_responses
  for select
  using (true);

-- 5. Create helpful indexes for filtering by condition or date
create index if not exists idx_experiment_responses_pid on public.experiment_responses (participant_id);
create index if not exists idx_experiment_responses_condition on public.experiment_responses (assigned_condition);
create index if not exists idx_experiment_responses_created_at on public.experiment_responses (created_at desc);

-- 6. Grant permissions to standard anon/authenticated roles
grant usage on schema public to anon, authenticated;
grant all on table public.experiment_responses to anon, authenticated;
grant all on sequence public.experiment_responses_id_seq to anon, authenticated;
